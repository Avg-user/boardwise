import { useQueries, useQuery } from '@tanstack/react-query'
import type { ReactNode } from 'react'
import { useTranslation } from 'react-i18next'
import { Link } from 'react-router-dom'
import { listTimeline } from '../../api/cases.ts'
import type { ChatMessage, Conversation, TimelineEntry } from '../../api/types.ts'
import { conversationsQuery, messagesQuery, SESSION_PARAM } from './useConversation.ts'

type CaseTimelineProps = {
  caseId: number
  /** The chat session currently open, marked in the list. */
  activeConversationId?: number | null
  /** Called when a chat is chosen, for example to switch to the Chat tab on phones. */
  onSessionSelect?: () => void
  /** When false, chats are listed but can't be opened, as in the My issues overview. */
  linkSessions?: boolean
  /** Shows Edit and Delete on each entry. Leave out for read-only views. */
  onEditEntry?: (entry: TimelineEntry) => void
  onDeleteEntry?: (entry: TimelineEntry) => void
}

function Tag({ label }: { label: string }) {
  return (
    <>
      {' '}
      <span className="timeline__tag">{label}</span>
    </>
  )
}

type TimelineItem =
  | { kind: 'entry'; key: string; sortKey: string; entry: TimelineEntry; sessionId: number | null }
  | { kind: 'session'; key: string; sortKey: string; conversation: Conversation }

/**
 * A case's timeline, oldest first. Each chat session is an entry: it's created with the
 * chat's first message, and clicking it opens that chat. Entries without a chat (added by
 * hand earlier, or generated by the AI) are listed too, as are older chats that never got
 * an entry.
 */
function CaseTimeline({
  caseId,
  activeConversationId,
  onSessionSelect,
  linkSessions = true,
  onEditEntry,
  onDeleteEntry,
}: CaseTimelineProps) {
  const { t, i18n } = useTranslation()
  const entries = useQuery({
    queryKey: ['cases', caseId, 'timeline'],
    queryFn: () => listTimeline(caseId),
  })
  const conversations = useQuery(conversationsQuery(caseId))
  // A chat can exist with no messages, for example when sending the first one failed.
  // Those are left off, since there's nothing to look back at.
  const messageCounts = useQueries({
    queries: (conversations.data ?? []).map((conversation) => ({
      ...messagesQuery(caseId, conversation.id),
      select: (messages: ChatMessage[]) => messages.length,
    })),
  })

  // Entries have no time of day, so format them in UTC to keep them from shifting a day.
  const dateFormat = new Intl.DateTimeFormat(i18n.resolvedLanguage, {
    dateStyle: 'medium',
    timeZone: 'UTC',
  })
  const dateTimeFormat = new Intl.DateTimeFormat(i18n.resolvedLanguage, {
    dateStyle: 'medium',
    timeStyle: 'short',
  })

  // Wait for the message counts too, so chats don't pop in after the entries.
  if (entries.isLoading || conversations.isLoading || messageCounts.some((query) => query.isLoading)) {
    return <p role="status">{t('common.loading')}</p>
  }
  if (entries.isError || conversations.isError) {
    return (
      <p className="form-error" role="alert">
        {t('common.serverError')}
      </p>
    )
  }

  // The server links each chat to its entry, so every device shows the same list.
  const closed = new Set(
    (conversations.data ?? []).filter((item) => item.closed_at !== null).map((item) => item.id),
  )
  const conversationIds = new Set((conversations.data ?? []).map((conversation) => conversation.id))
  const linkedSessions = new Set(
    (entries.data ?? []).flatMap((entry) =>
      entry.conversation !== null && conversationIds.has(entry.conversation) ? [entry.conversation] : [],
    ),
  )

  const items: TimelineItem[] = [
    ...(entries.data ?? []).map((entry) => ({
      kind: 'entry' as const,
      key: `entry-${entry.id}`,
      sortKey: `${entry.occurred_at}T${entry.created_at}`,
      entry,
      sessionId: entry.conversation !== null && conversationIds.has(entry.conversation) ? entry.conversation : null,
    })),
    ...(conversations.data ?? [])
      .filter((conversation, index) => {
        const hasMessages = (messageCounts[index]?.data ?? 0) > 0
        return hasMessages && !linkedSessions.has(conversation.id)
      })
      .map((conversation) => ({
        kind: 'session' as const,
        key: `session-${conversation.id}`,
        sortKey: `${conversation.created_at.slice(0, 10)}T${conversation.created_at}`,
        conversation,
      })),
  ].sort((a, b) => a.sortKey.localeCompare(b.sortKey))

  if (items.length === 0) {
    return <p className="placeholder-notice">{t('case.timelineEmpty')}</p>
  }

  function chatTags(sessionId: number) {
    return (
      <>
        <Tag label={closed.has(sessionId) ? t('timeline.closedTag') : t('timeline.openTag')} />
        {linkSessions && sessionId === activeConversationId && <Tag label={t('timeline.viewing')} />}
      </>
    )
  }

  function chatLink(sessionId: number, children: ReactNode) {
    return (
      <Link
        className="timeline__session"
        to={`/cases/${caseId}?${SESSION_PARAM}=${sessionId}`}
        aria-current={sessionId === activeConversationId ? 'true' : undefined}
        onClick={onSessionSelect}
      >
        {children}
      </Link>
    )
  }

  return (
    <ol className="timeline">
      {items.map((item) => {
        if (item.kind === 'session') {
          const body = (
            <>
              <time dateTime={item.conversation.created_at}>
                {dateTimeFormat.format(new Date(item.conversation.created_at))}
              </time>
              <span className="timeline__title">
                {t('timeline.chatSession')}
                {chatTags(item.conversation.id)}
              </span>
            </>
          )
          return (
            <li key={item.key} className="timeline__item timeline__item--session">
              {linkSessions ? chatLink(item.conversation.id, body) : body}
            </li>
          )
        }

        const { entry, sessionId } = item
        const body = (
          <>
            <time dateTime={entry.occurred_at}>{dateFormat.format(new Date(entry.occurred_at))}</time>
            <span className="timeline__title">
              {entry.title}
              {entry.source === 'ai' && <Tag label={t('timeline.aiTag')} />}
              {sessionId !== null && chatTags(sessionId)}
            </span>
            {entry.description && <span className="field-hint">{entry.description}</span>}
          </>
        )
        return (
          <li
            key={item.key}
            className={`timeline__item${sessionId !== null ? ' timeline__item--chat' : ''}`}
          >
            {sessionId !== null && linkSessions ? chatLink(sessionId, body) : body}
            {(onEditEntry || onDeleteEntry) && (
              <span className="timeline__actions">
                {onEditEntry && (
                  <button
                    type="button"
                    className="button-quiet"
                    aria-label={t('entry.editNamed', { title: entry.title })}
                    onClick={() => onEditEntry(entry)}
                  >
                    {t('entry.edit')}
                  </button>
                )}
                {onDeleteEntry && (
                  <button
                    type="button"
                    className="button-quiet"
                    aria-label={t('entry.deleteNamed', { title: entry.title })}
                    onClick={() => onDeleteEntry(entry)}
                  >
                    {t('entry.delete')}
                  </button>
                )}
              </span>
            )}
          </li>
        )
      })}
    </ol>
  )
}

export default CaseTimeline
